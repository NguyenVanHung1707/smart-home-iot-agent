class ReviewToolCall(BaseModel):
    """One runtime tool call the corpus expects, or forbids, for a case."""

    model_config = ConfigDict(extra="forbid", frozen=True, strict=True)

    name: str = Field(min_length=1)
    args: dict[str, Any] = Field(default_factory=dict)


class ReviewCase(BaseModel):
    """Một ca vàng không thực thi, mô tả hành vi bằng lời gọi tool."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    id: str = Field(pattern=r"^[a-z0-9-]+$")
    description: str = Field(min_length=1)
    utterance: str = Field(min_length=1)
    categories: frozenset[str] = Field(min_length=1)
    expected_act: ReviewAct
    safety_class: ReviewSafetyClass
    expected_tool_calls: tuple[ReviewToolCall, ...] = ()
    required_concepts: tuple[ReviewConcept, ...] = Field(min_length=1)
    forbidden_concepts: tuple[ReviewConcept, ...] = Field(min_length=1)
    notes: str = ""


REVIEW_CASE_SCHEMA: Final = {
    "id": "stable kebab-case id",
    "description": "short human-readable purpose",
    "utterance": "Vietnamese user input under review",
    "categories": ["taxonomy labels covered by the case"],
    "expected_act": "CONTROL | CLARIFY | INFORM | REFUSE",
    "safety_class": "ROUTINE | READ_ONLY | AMBIGUOUS | UNSUPPORTED | SENSITIVE | ADVERSARIAL",
    "expected_tool_calls": [{"name": "tool_name", "args": {"arg": "value"}}],
    "required_concepts": ["concepts expected in the response or decision"],
    "forbidden_concepts": ["concepts that must not appear in the response or decision"],
    "notes": "review guidance; no secrets",
}


def _call(name: str, **args: Any) -> dict[str, Any]:
    return {"name": name, "args": args}


def _case(
    case_id: str,
    description: str,
    utterance: str,
    categories: tuple[str, ...],
    expected_act: str,
    safety_class: str,
    expected_tool_calls: tuple[dict[str, Any], ...],
    required_concepts: tuple[str, ...],
    forbidden_concepts: tuple[str, ...],
    notes: str,
) -> dict[str, Any]:
    return {
        "id": case_id,
        "description": description,
        "utterance": utterance,
        "categories": list(categories),
        "expected_act": expected_act,
        "safety_class": safety_class,
        "expected_tool_calls": list(expected_tool_calls),
        "required_concepts": list(required_concepts),
        "forbidden_concepts": list(forbidden_concepts),
        "notes": notes,
    }


