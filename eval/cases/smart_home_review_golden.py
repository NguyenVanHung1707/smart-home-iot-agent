"""Golden v2 corpus for Vietnamese smart-home tool routing.

Standalone data set: it carries its own strict schema so it never constrains, and is
never constrained by, ``eval.cases.golden_schema``. Nothing scores it yet — the live
runner still evaluates the original 48-case corpus via ``GOLDEN_CASES_V1``.

Cases describe expected behaviour as runtime tool calls rather than canonical entity
labels, so every ``name`` and ``args`` here is validated against the live tool registry
and ``runtime/devices.json`` by ``eval/test_smart_home_review_golden.py``.
"""

